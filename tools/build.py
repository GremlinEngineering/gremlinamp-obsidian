#!/usr/bin/env python3
"""Build the standard Obsidian release and its manual-install ZIP offline."""
import argparse
import base64
import json
import re
import shutil
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile

root = Path(__file__).resolve().parents[1]
runtime = root / 'decoder-runtime'


def bundle_assets():
    assets = {}
    workers = {}
    for script in sorted(runtime.glob('*-worker.js')):
        code = script.read_text()
        # The original site workers address their siblings relative to their runtime.
        code = code.replace('self.location.href', 'decoderBase')
        assets[script.name] = code.encode()
        files = set()
        for ref in re.findall(r"['\"](?:\./)?(vendor/[^'\"]+)['\"]", code):
            path = runtime / ref
            if ref.endswith('/') and ref != 'vendor/':
                files.update(file for file in path.iterdir() if file.suffix in {'.js', '.wasm', '.data'})
            elif not ref.endswith('/'):
                files.add(path)
                # Factory builds may load the associated WASM by its basename.
                if path.suffix == '.js' and path.with_suffix('.wasm').exists():
                    files.add(path.with_suffix('.wasm'))
        workers[script.name] = sorted(file.relative_to(runtime).as_posix() for file in files)
        if not files:
            raise ValueError(f'{script.name} has no bundled decoder assets')
        assets.update((file.relative_to(runtime).as_posix(), file.read_bytes()) for file in files)
    return {name: base64.b64encode(data).decode('ascii') for name, data in sorted(assets.items())}, workers


def build(directory):
    manifest = json.loads((root / 'manifest.json').read_text())
    plugin_id = manifest['id']
    target = directory / plugin_id
    target.mkdir(parents=True, exist_ok=True)
    assets, workers = bundle_assets()
    routes = (runtime / 'decoders.js').read_text().replace('export ', '')
    inputs = ['strings.js', 'formats.js', 'worker-host.js', 'playback.js', 'main.js']
    parts = [
        '// Generated by tools/build.py. Source and decoder notices are shipped in the project repository.',
        "'use strict';",
        'const bundledAssets = ' + json.dumps(assets, separators=(',', ':')) + ';',
        'const decoderAssetsByWorker = ' + json.dumps(workers, separators=(',', ':')) + ';',
        routes,
        *((root / 'src' / name).read_text() for name in inputs),
    ]
    with (target / 'main.js').open('w', encoding='utf-8', newline='\n') as output:
        for part in parts:
            output.write(part + '\n')
    for name in ('manifest.json', 'styles.css'):
        shutil.copyfile(root / name, target / name)
    archive_path = directory / f'{plugin_id}-{manifest["version"]}.zip'
    with ZipFile(archive_path, 'w', ZIP_DEFLATED, compresslevel=6) as archive:
        for name in ('main.js', 'manifest.json', 'styles.css'):
            archive.write(target / name, f'{plugin_id}/{name}')
        archive.write(root / 'THIRD_PARTY_NOTICES.md', f'{plugin_id}/THIRD_PARTY_NOTICES.md')
        archive.write(root / 'LICENSE', f'{plugin_id}/LICENSE')
        for notice in sorted((runtime / 'vendor').rglob('*')):
            if notice.is_file() and notice.suffix not in {'.js', '.wasm', '.data'}:
                archive.write(notice, f'{plugin_id}/notices/{notice.relative_to(runtime / "vendor").as_posix()}')
    print(archive_path, len(assets), 'embedded files')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path, default=root / 'dist')
    build(parser.parse_args().out)
